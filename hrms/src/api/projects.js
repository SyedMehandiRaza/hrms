import client from "./client";

// Project endpoints (backend/src/routes/project.routes.js, workforce D7–D16, ADR 0010).
// Each returns the response's `data`. Errors are axios errors: read them with
// utils/apiError.js / utils/applyFieldErrors.js.
//
// A project item: { id, name, code ("PRJ-FY26-0001"), description, location, latitude, longitude,
//   radius, allow_offline_attendance, start_date, end_date, status ("ACTIVE"|"ON_HOLD"|"COMPLETED"),
//   photo ("/uploads/..." or null — use assetUrl), office: { id, name, location } | null,
//   country: { id, iso2, name } | null, city: { id, name } | null, employee_count,
//   contract_employee_count, created_at, updated_at }

// GET /projects?page=&limit=&search=&status= ("" = no filter), newest first →
//   { items, total, page, limit, stats: { total_projects, active_projects, on_hold_projects,
//     completed_projects, total_employees } }
export const listProjects = ({ page = 1, limit = 10, search = "", status = "" } = {}) =>
  client.get("/projects", { params: { page, limit, search, status } }).then((res) => res.data.data);

// GET /projects/:id → the item.
export const getProject = (id) => client.get(`/projects/${encodeURIComponent(id)}`).then((res) => res.data.data);

// GET /projects/office-options?projectId= → [{ id, name, location }]: head offices without a project,
// plus the project's own office when editing (D12).
export const listOfficeOptions = (projectId) =>
  client.get("/projects/office-options", { params: projectId ? { projectId } : {} }).then((res) => res.data.data);

// POST /projects → the new item (the code is generated by the server).
// Body: { name, officeId, startDate, endDate, location, latitude, longitude, radius,
//   allowOfflineAttendance, description?, countryId, cityId?, status? }.
// 409 PROJECT_NAME_TAKEN, PROJECT_OFFICE_TAKEN.
export const createProject = (body) => client.post("/projects", body).then((res) => res.data.data);

// PUT /projects/:id → the item. Same body as create.
// 409 also PROJECT_HAS_EMPLOYEES (completing someone's main project), PROJECT_START_AFTER_ASSIGNMENTS.
export const updateProject = (id, body) =>
  client.put(`/projects/${encodeURIComponent(id)}`, body).then((res) => res.data.data);

// PUT /projects/:id/image, multipart field `image` (JPG/PNG ≤ 2 MB) → the item.
// 400 PROJECT_IMAGE_INVALID.
export const uploadProjectImage = (id, file) => {
  const form = new FormData();
  form.append("image", file);
  return client.put(`/projects/${encodeURIComponent(id)}/image`, form).then((res) => res.data.data);
};

// DELETE /projects/:id/image → the item (photo null).
export const removeProjectImage = (id) =>
  client.delete(`/projects/${encodeURIComponent(id)}/image`).then((res) => res.data.data);

// ── Workforce (D13–D15) ──
// A member: { id, employee_code, name, role, access_level, employment_type, staffing_company,
//   employment_status ("ACTIVE"|"IN_NOTICE"), is_main, start_date }

// GET /projects/:id/employees?page=&limit=&search=&status= (ACTIVE | IN_NOTICE | "") → { items, total, page, limit }
export const listProjectWorkforce = (id, { page = 1, limit = 20, search = "", status = "" } = {}) =>
  client
    .get(`/projects/${encodeURIComponent(id)}/employees`, { params: { page, limit, search, status } })
    .then((res) => res.data.data);

// GET /projects/:id/assignable-employees?search=&page=&limit= → { items: [{ id, employee_code, name,
//   employment_type }], total, page, limit }: active employees not on the project yet.
export const listAssignableEmployees = (id, { page = 1, limit = 100, search = "" } = {}) =>
  client
    .get(`/projects/${encodeURIComponent(id)}/assignable-employees`, { params: { page, limit, search } })
    .then((res) => res.data.data);

// POST /projects/:id/employees { employeeIds } → { assigned }. All or nothing.
// 409 PROJECT_NOT_ACTIVE, PROJECT_GENERAL_EMPLOYEE_SINGLE.
export const assignProjectEmployees = (id, employeeIds) =>
  client.post(`/projects/${encodeURIComponent(id)}/employees`, { employeeIds }).then((res) => res.data.data);

// DELETE /projects/:id/employees/:employeeId → { id }. 409 PROJECT_REMOVE_MAIN.
export const removeProjectEmployee = (id, employeeId) =>
  client
    .delete(`/projects/${encodeURIComponent(id)}/employees/${encodeURIComponent(employeeId)}`)
    .then((res) => res.data.data);
